#!/bin/bash
# ABOUTME: Integration tests: the real vpn-manager, vpn-kill-switch and vpn-utils keep and release VPN DNS
# ABOUTME: Covers the kill -9 path and `vpn cleanup` (#295 FR5) on a fake firewall, openresolv and processes
# shellcheck disable=SC2319  # `report $?` deliberately reports the [[ ]] check above it

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
SRC_DIR="$PROJECT_ROOT/src"

TESTS_RUN=0
TESTS_PASSED=0
TESTS_FAILED=0
declare -a FAILED_TESTS=()

T_GREEN='\033[1;32m'
T_RED='\033[1;31m'
T_BLUE='\033[1;34m'
T_NC='\033[0m'

test_pass() {
    TESTS_RUN=$((TESTS_RUN + 1))
    TESTS_PASSED=$((TESTS_PASSED + 1))
    echo -e "  ${T_GREEN}✓${T_NC} $1"
}

test_fail() {
    TESTS_RUN=$((TESTS_RUN + 1))
    TESTS_FAILED=$((TESTS_FAILED + 1))
    FAILED_TESTS+=("$1")
    echo -e "  ${T_RED}✗${T_NC} $1"
    [[ -n "${2:-}" ]] && echo -e "    $2"
}

# report <exit-code> <name> [detail]
report() {
    if [[ $1 -eq 0 ]]; then
        test_pass "$2"
    else
        test_fail "$2" "${3:-}"
    fi
}

WORK_DIR=$(mktemp -d)
DECOY_PID=""
FAKE_PIDS="$WORK_DIR/fake_pids" # every fake OpenVPN started, also from subshells
cleanup_work_dir() {
    local pid
    [[ -n $DECOY_PID ]] && kill "$DECOY_PID" 2> /dev/null
    if [[ -f $FAKE_PIDS ]]; then
        while read -r pid; do
            [[ -n $pid ]] && kill "$pid" 2> /dev/null
        done < "$FAKE_PIDS"
    fi
    rm -rf "$WORK_DIR"
}
trap cleanup_work_dir EXIT

# Sandbox: a PATH made of the fakes plus every system tool except those that
# touch the firewall, DNS, the network, processes or privileges. sudo resets
# PATH, so the fake sudo runs only the fakes and records anything else.
FW="$WORK_DIR/fw"         # fake firewall state (FAKE_FW_DIR)
FAKES="$WORK_DIR/fakes"   # first on PATH
SYSBIN="$WORK_DIR/sysbin" # system tools minus the denied ones
CALLS="$WORK_DIR/calls.log"
LINKS="$WORK_DIR/links"       # interfaces the fake ip reports (files: tun0, wg0 = wireguard)
PROCS="$WORK_DIR/procs"       # PIDs the fake pgrep reports as openvpn
RC_DIR="$WORK_DIR/rc_entries" # fake openresolv's registered entries
RESOLV="$WORK_DIR/resolv.conf"
NM_RESOLV="$WORK_DIR/nm-resolv.conf"
PID_FILE="$WORK_DIR/openvpn.pid"
SIG="# Generated by resolvconf"
VPN_NS=10.96.0.1  # the VPN's pushed DNS server
LAN_NS=192.0.2.53 # NetworkManager's (router) DNS server
mkdir -p "$FAKES" "$SYSBIN"
ln -s /usr/bin/* "$SYSBIN"/ 2> /dev/null
DENIED=(iptables ip6tables iptables-restore ip6tables-restore iptables-save ip6tables-save
    iptables-nft ip6tables-nft iptables-legacy ip6tables-legacy xtables-nft-multi
    xtables-legacy-multi nft ip sudo doas su pkexec resolvconf nmcli tailscale openvpn
    wg wg-quick systemctl rc-service sv pgrep pkill kill killall ps logger notify-send)
for tool in "${DENIED[@]}"; do
    rm -f "$SYSBIN/$tool"
done
for tool in iptables ip6tables iptables-restore ip6tables-restore; do
    ln -s "$PROJECT_ROOT/tests/fakes/fake-firewall" "$FAKES/$tool"
done

# openresolv with its real rule: -a/-d only rewrite resolv.conf when its first
# line is openresolv's signature, -u always does; an exclusive (-x) entry wins
cat > "$FAKES/resolvconf" << 'EOF'
#!/bin/bash
regen() { # $1 = force
    if [[ $1 != force && -s $RESOLV && $(head -1 "$RESOLV") != "$SIG" ]]; then
        echo "resolvconf: signature mismatch: $RESOLV" >&2
        return 1
    fi
    local excl
    excl=$(ls "$RC_DIR"/*.excl 2> /dev/null | head -1)
    {
        echo "$SIG"
        if [[ -n $excl ]]; then
            cat "${excl%.excl}"
        else
            for e in "$RC_DIR"/*; do [[ -f $e && $e != *.excl ]] && cat "$e"; done
        fi
    } > "$RESOLV"
}
case "$1" in
    -i) ls "$RC_DIR" | grep -v '\.excl$' | tr '\n' ' '; exit 0 ;;
    -l) cat "$RC_DIR/$2" 2> /dev/null; exit 0 ;;
esac
echo "resolvconf:$*" >> "$CALLS"
x="" f=""
while [[ $1 == -x || $1 == -f ]]; do
    [[ $1 == -x ]] && x=1
    [[ $1 == -f ]] && f=1
    shift
done
case "$1" in
    -a) cat > "$RC_DIR/$2"; rm -f "$RC_DIR/$2.excl"; [[ -n $x ]] && touch "$RC_DIR/$2.excl"; regen ;;
    -d) [[ -e $RC_DIR/$2 || -n $f ]] || exit 1; rm -f "$RC_DIR/$2" "$RC_DIR/$2.excl"; regen ;;
    -u) regen force ;;
esac
EOF
cat > "$FAKES/sudo" << 'EOF'
#!/bin/bash
[[ $1 == -n ]] && shift
case "$1" in
    true | iptables | ip6tables | iptables-restore | ip6tables-restore | resolvconf | ip) exec "$@" ;;
    install | rm)
        # Only paths inside the test directory, never through ..
        for a in "${@:2}"; do
            [[ ($a != */* || $a == "$WORK_DIR"/*) && $a != *..* ]] || { echo "sudo:$*" >> "$CALLS"; exit 1; }
        done
        exec "$@"
        ;;
esac
echo "sudo:$*" >> "$CALLS"
exit 1
EOF
cat > "$FAKES/ip" << 'EOF'
#!/bin/bash
args=" $* "
if [[ $args == *" link show "* ]]; then
    if [[ $args == *" type wireguard "* ]]; then
        [[ -e $LINKS/wg0 ]] && echo "9: wg0: <POINTOPOINT,NOARP,UP,LOWER_UP> mtu 1420"
        exit 0
    fi
    # ip link show <dev>: that device; ip link show: every device
    dev=${*: -1}
    if [[ $dev != show ]]; then
        [[ -e $LINKS/$dev ]] || exit 1
        echo "5: $dev: <POINTOPOINT,MULTICAST,NOARP,UP,LOWER_UP> mtu 1500"
        exit 0
    fi
    echo "1: lo: <LOOPBACK,UP,LOWER_UP> mtu 65536"
    for f in "$LINKS"/*; do [[ -e $f ]] && echo "5: $(basename "$f"): <UP> mtu 1500"; done
    exit 0
fi
echo "ip:$*" >> "$CALLS"
exit 0
EOF
# Only the test's fake OpenVPN processes exist ($PROCS, while still alive)
cat > "$FAKES/pgrep" << 'EOF'
#!/bin/bash
[[ $* == *openvpn* ]] || exit 1
found=1
while read -r pid; do
    [[ -n $pid && -d /proc/$pid ]] && { echo "$pid"; found=0; }
done < "$PROCS"
exit $found
EOF
# ps -p <pid> [-o args=]: only for those processes; process lists are empty
cat > "$FAKES/ps" << 'EOF'
#!/bin/bash
[[ $1 == -p ]] || exit 1
grep -qx -- "$2" "$PROCS" && [[ -d /proc/$2 ]] || exit 1
[[ $* == *args=* ]] && tr '\0' ' ' < "/proc/$2/cmdline"
exit 0
EOF
for tool in pkill kill logger notify-send; do
    printf '#!/bin/bash\necho "%s:$*" >> "$CALLS"\n' "$tool" > "$FAKES/$tool"
done
chmod +x "$FAKES"/*
SANDBOX_PATH="$FAKES:$SYSBIN"

# A process that is not OpenVPN, for the stale PID file: it must survive
sleep 600 &
DECOY_PID=$!

# A stand-in OpenVPN: argv says ".../openvpn --config ...", but its kernel
# command name is sleep, so nothing ever escalates to sudo for it. Started
# from a subshell so that, once signalled, it is reaped and leaves no zombie.
# Its argv matches the real pgrep pattern, so it must never outlive the run:
# every PID goes to $FAKE_PIDS for the EXIT trap, and it exits on its own
# after 2 minutes at the latest.
FAKE_OPENVPN_PID=""
start_fake_openvpn() {
    mkdir -p "$WORK_DIR/fake"
    FAKE_OPENVPN_PID=$(
        bash -c 'exec -a "$0 --config $1" sleep 120' "$WORK_DIR/fake/openvpn" \
            "$WORK_DIR/session/profile.ovpn" > /dev/null 2>&1 &
        echo $!
    )
    echo "$FAKE_OPENVPN_PID" >> "$FAKE_PIDS"
    echo "$FAKE_OPENVPN_PID" >> "$PROCS"
}

# Stop every fake OpenVPN of the current state ($PROCS)
stop_fake_openvpns() {
    local pid
    while read -r pid; do
        [[ -n $pid ]] && kill "$pid" 2> /dev/null
    done < "$PROCS"
    return 0
}

reset_state() {
    [[ -f $PROCS ]] && stop_fake_openvpns
    rm -rf "${WORK_DIR:?}"/{fw,links,rc_entries,home,run,session}
    mkdir -p "$FW" "$LINKS" "$RC_DIR" "$WORK_DIR/home/.config/vpn" "$WORK_DIR/run" "$WORK_DIR/session"
    chmod 700 "$WORK_DIR/run"
    : > "$CALLS"
    : > "$PROCS"
    : > "$WORK_DIR/home/.config/vpn/config"
    rm -f "$PID_FILE"
    printf 'nameserver %s\n' "$LAN_NS" > "$NM_RESOLV"
    printf '%s\n' "$SIG" > "$RESOLV"
}

# Run a script from src/ in the sandbox, unprivileged (through the fake sudo)
# Args: $1 = script in src/ (or an absolute path), rest = its arguments;
# extra environment via RUN_ENV (array)
RUN_ENV=()
run_src() {
    local script=$SRC_DIR/$1
    [[ $1 == /* ]] && script=$1
    shift
    env -i HOME="$WORK_DIR/home" PATH="$SANDBOX_PATH" TERM=dumb \
        FAKE_FW_DIR="$FW" CALLS="$CALLS" LINKS="$LINKS" PROCS="$PROCS" \
        RC_DIR="$RC_DIR" RESOLV="$RESOLV" SIG="$SIG" WORK_DIR="$WORK_DIR" \
        XDG_STATE_HOME="$WORK_DIR/home/.local/state" XDG_CACHE_HOME="$WORK_DIR/home/.cache" \
        XDG_CONFIG_HOME="$WORK_DIR/home/.config" XDG_RUNTIME_DIR="$WORK_DIR/run" \
        VPN_SESSION_DIR="$WORK_DIR/session" VPN_CONFIG_DIR="$WORK_DIR/home/.config/vpn" \
        VPN_RESOLV_CONF="$RESOLV" VPN_NM_RESOLV_CONF="$NM_RESOLV" VPN_PID_FILE="$PID_FILE" \
        VPN_DNS_HELPER="$WORK_DIR/no-dns-helper" VPN_TAILSCALE_TAKEOVER_WAIT=1 \
        "${RUN_ENV[@]}" "$BASH" "$script" "$@"
}

ks() { run_src vpn-kill-switch "$@"; }

# Register an openresolv entry. Args: $1 = name, $2 = nameserver, $3 = -x (exclusive)
rc_add() {
    printf 'nameserver %s\n' "$2" | env PATH="$SANDBOX_PATH" CALLS="$WORK_DIR/setup.log" \
        RC_DIR="$RC_DIR" RESOLV="$RESOLV" SIG="$SIG" "$FAKES/resolvconf" ${3:+"$3"} -a "$1"
}

# The fake table, as iptables -S prints it. Args: $1 = v4|v6, $2 = chain (optional)
fw_rules() {
    local tool=iptables
    [[ $1 == v6 ]] && tool=ip6tables
    env PATH="$SANDBOX_PATH" FAKE_FW_DIR="$FW" "$FAKES/$tool" -S ${2:+"$2"} 2> /dev/null
}

# Any trace of a chain in family $1: its rules or a jump to it
chain_present() { fw_rules "$1" | grep -q -- "$2"; }

dns_guard_present() { chain_present v4 VPN_DNS_GUARD || chain_present v6 VPN_DNS_GUARD; }

# The state OpenVPN leaves when it is killed with SIGKILL: its tunnel is gone,
# but the DNS entry, the guards and (optionally) the kill switch remain, and
# the PID file names a PID that is now someone else's.
# Args: $1 = with-nm-entry (the FR2 drop-in is installed) | no-nm-entry,
#       $2 = kill-switch | no-kill-switch
kill_9_state() {
    reset_state
    [[ $1 == with-nm-entry ]] && rc_add NetworkManager "$LAN_NS"
    rc_add tun0.protonvpn "$VPN_NS" -x
    touch "$LINKS/tun0"
    ks ipv6-guard on > /dev/null 2>&1
    ks dns-guard on > /dev/null 2>&1
    [[ $2 == kill-switch ]] && ks enable 198.51.100.7 > /dev/null 2>&1
    rm -f "$LINKS/tun0"
    echo "$DECOY_PID" > "$PID_FILE"
    : > "$CALLS"
}

# ---------------------------------------------------------------------------
# The sandbox itself
# ---------------------------------------------------------------------------
test_sandbox() {
    local tool found bad=""
    for tool in iptables ip6tables iptables-restore ip6tables-restore sudo resolvconf ip pgrep ps kill pkill; do
        # type -P: the program, not a shell builtin (kill)
        found=$(env PATH="$SANDBOX_PATH" bash -c "type -P $tool")
        [[ $found == "$FAKES/$tool" ]] || bad+=" $tool=$found"
    done
    for tool in nmcli nft tailscale openvpn wg-quick; do
        found=$(env PATH="$SANDBOX_PATH" bash -c "command -v $tool")
        [[ -z $found ]] || bad+=" $tool=$found"
    done
    [[ -z $bad ]]
    report $? "only the fakes are reachable for the firewall, DNS, processes and sudo" "$bad"
}

# ---------------------------------------------------------------------------
# FR5: after kill -9, `vpn cleanup` removes the stale DNS entry and the guard
# ---------------------------------------------------------------------------
test_kill_9_state_reproduced() {
    kill_9_state with-nm-entry kill-switch
    [[ -e $RC_DIR/tun0.protonvpn ]] && grep -qx "nameserver $VPN_NS" "$RESOLV"
    report $? "kill -9 state: the VPN's entry is registered and resolv.conf is on its DNS" \
        "$(ls "$RC_DIR"; cat "$RESOLV")"
    chain_present v4 VPN_DNS_GUARD && chain_present v6 VPN_DNS_GUARD
    report $? "kill -9 state: the DNS guard is loaded in both families" "$(fw_rules v4; fw_rules v6)"
    ks is-enabled > /dev/null 2>&1 && [[ ! -s $PROCS ]]
    report $? "kill -9 state: the kill switch is on and no openvpn runs"
}

# Args: $1 = with-nm-entry | no-nm-entry, $2 = kill-switch | no-kill-switch
test_cleanup_after_kill_9() {
    kill_9_state "$1" "$2"
    local out rc=0
    out=$(run_src vpn cleanup 2>&1) || rc=$?
    local what="($1, $2)"
    [[ $rc -eq 0 ]]
    report $? "vpn cleanup after kill -9 exits 0 $what" "exit $rc: $out"
    [[ ! -e $RC_DIR/tun0.protonvpn ]]
    report $? "vpn cleanup removes the stale tun0.protonvpn entry $what" "$(ls "$RC_DIR"; cat "$CALLS")"
    ! dns_guard_present
    report $? "vpn cleanup removes the DNS guard and every jump to it $what" "$(fw_rules v4; fw_rules v6)"
    ! chain_present v6 VPN_IPV6_GUARD
    report $? "vpn cleanup removes the IPv6 guard $what" "$(fw_rules v6)"
    ! ks is-enabled > /dev/null 2>&1
    report $? "vpn cleanup leaves no kill switch $what" "$(fw_rules v4)"
    ! grep -q "$VPN_NS" "$RESOLV" && grep -qx "nameserver $LAN_NS" "$RESOLV"
    report $? "resolv.conf is back on the system's DNS $what" "$(cat "$RESOLV")"
    # kill is a builtin: only the decoy surviving proves it was not signalled
    kill -0 "$DECOY_PID" 2> /dev/null && ! grep -qE '^(sudo:kill|pkill)' "$CALLS"
    report $? "the stale PID file's process is never signalled $what" "$(cat "$CALLS")"
    [[ -e $RC_DIR/NetworkManager || $1 == no-nm-entry ]]
    report $? "NetworkManager's own entry is left alone $what" "$(ls "$RC_DIR")"
}

# #295: NetworkManager rewrote resolv.conf while connected (no drop-in), so
# openresolv refuses -d on the foreign file. Cleanup must still not fail.
test_cleanup_foreign_resolv_conf() {
    kill_9_state no-nm-entry no-kill-switch
    printf '# Generated by NetworkManager\nnameserver %s\n' "$LAN_NS" > "$RESOLV"
    local rc=0
    run_src vpn cleanup > /dev/null 2>&1 || rc=$?
    [[ $rc -eq 0 && ! -e $RC_DIR/tun0.protonvpn ]] && ! dns_guard_present
    report $? "foreign resolv.conf: cleanup still removes the entry and the guard" \
        "exit $rc; $(ls "$RC_DIR"; fw_rules v4)"
    grep -qx "nameserver $LAN_NS" "$RESOLV" && ! grep -q "$VPN_NS" "$RESOLV"
    report $? "foreign resolv.conf: it keeps the system's DNS" "$(cat "$RESOLV")"
}

# The PID file names an OpenVPN that still runs (the tunnel died, the process
# hangs): cleanup verifies it through ps, stops it, and only then releases
test_cleanup_stops_hung_openvpn() {
    kill_9_state with-nm-entry kill-switch
    start_fake_openvpn
    echo "$FAKE_OPENVPN_PID" > "$PID_FILE"
    local rc=0
    run_src vpn cleanup > /dev/null 2>&1 || rc=$?
    [[ $rc -eq 0 && ! -d /proc/$FAKE_OPENVPN_PID ]] && kill -0 "$DECOY_PID" 2> /dev/null
    report $? "cleanup stops the OpenVPN the PID file names, and nothing else" "exit $rc; $(cat "$CALLS")"
    [[ ! -e $RC_DIR/tun0.protonvpn ]] && ! dns_guard_present && ! ks is-enabled > /dev/null 2>&1
    report $? "after stopping it, cleanup releases the entry, the guard and the kill switch" \
        "$(ls "$RC_DIR"; fw_rules v4)"
}

# A WireGuard tunnel is a VPN that is still up: its state is not stale
test_cleanup_keeps_state_of_running_wireguard() {
    kill_9_state with-nm-entry no-kill-switch
    touch "$LINKS/wg0"
    run_src vpn cleanup > /dev/null 2>&1
    [[ -e $RC_DIR/tun0.protonvpn ]] && dns_guard_present
    report $? "cleanup leaves DNS and the guard alone while a WireGuard tunnel is up" \
        "$(ls "$RC_DIR"; fw_rules v4)"
}

# The stale-state check on connect: a tun0 that still exists means a VPN may
# still run where pgrep cannot see it (root OpenVPN with /proc hidepid), so
# its protection stays (fail closed)
STALE_DRIVER="$WORK_DIR/stale-driver"
cat > "$STALE_DRIVER" << 'EOF'
#!/bin/bash
# shellcheck disable=SC1091
source "$1/vpn-utils"
VPN_DIR=$1
clear_stale_vpn_state
EOF
test_stale_check_keeps_state_while_tun0_exists() {
    kill_9_state with-nm-entry kill-switch
    touch "$LINKS/tun0"
    run_src "$STALE_DRIVER" "$SRC_DIR" > /dev/null 2>&1
    [[ -e $RC_DIR/tun0.protonvpn ]] && dns_guard_present && ks is-enabled > /dev/null 2>&1
    report $? "stale check: tun0 still there with no visible openvpn keeps DNS, guard and kill switch" \
        "$(ls "$RC_DIR"; fw_rules v4)"

    rm -f "$LINKS/tun0"
    run_src "$STALE_DRIVER" "$SRC_DIR" > /dev/null 2>&1
    [[ ! -e $RC_DIR/tun0.protonvpn ]] && ! dns_guard_present
    report $? "stale check: with tun0 gone the state is released" "$(ls "$RC_DIR"; fw_rules v4)"
}

# ---------------------------------------------------------------------------
# Connect and disconnect (FR6, FR7)
# ---------------------------------------------------------------------------
# Jumps from OUTPUT, in order. Args: $1 = v4|v6
output_jumps() { fw_rules "$1" OUTPUT | sed -n 's/^-A OUTPUT -j //p'; }

# The connector's success path for real (IPv6 guard, Tailscale pause, DNS
# guard, then the kill switch), on a tunnel the fake OpenVPN holds. A small
# driver script sources the connector and runs that one function.
DRIVER="$WORK_DIR/connect-driver"
cat > "$DRIVER" << 'EOF'
#!/bin/bash
# shellcheck disable=SC1091
source "$1/vpn-connector" > /dev/null 2>&1
set +e
handle_connection_success prof 1 1 ""
EOF
connect() {
    reset_state
    rc_add NetworkManager "$LAN_NS"
    start_fake_openvpn
    touch "$LINKS/tun0"
    rc_add tun0.protonvpn "$VPN_NS" -x
    RUN_ENV=(VPN_KILL_SWITCH=1)
    run_src "$DRIVER" "$SRC_DIR"
    RUN_ENV=()
}

test_connect_sequence() {
    local out
    out=$(connect 2>&1)
    [[ $(output_jumps v4 | head -1) == VPN_DNS_GUARD && $(output_jumps v6 | head -1) == VPN_DNS_GUARD ]]
    report $? "connect: the DNS guard is the first OUTPUT jump in both families after the kill switch" \
        "v4: $(output_jumps v4 | tr '\n' ' ') v6: $(output_jumps v6 | tr '\n' ' '); $out"
    [[ $(output_jumps v4 | grep -cx VPN_DNS_GUARD) -eq 1 && $(output_jumps v6 | grep -cx VPN_DNS_GUARD) -eq 1 ]]
    report $? "connect: one jump to the DNS guard per family" "$(output_jumps v4; output_jumps v6)"
    output_jumps v4 | grep -qx VPN_KILL_SWITCH && output_jumps v6 | grep -qx VPN_IPV6_GUARD
    report $? "connect: the kill switch and the IPv6 guard are on too" "$(output_jumps v4; output_jumps v6); $out"
    stop_fake_openvpns
}

test_disconnect_removes_everything() {
    connect > /dev/null 2>&1
    local out rc=0
    out=$(run_src vpn disconnect 2>&1) || rc=$?
    [[ $rc -eq 0 && ! -d /proc/$FAKE_OPENVPN_PID ]]
    report $? "disconnect stops the fake OpenVPN and exits 0" "exit $rc: $out"
    ! fw_rules v4 | grep -q VPN_ && ! fw_rules v6 | grep -q VPN_
    report $? "disconnect removes every chain and jump in both families" "$(fw_rules v4; fw_rules v6)"
    [[ ! -e $RC_DIR/tun0.protonvpn && -e $RC_DIR/NetworkManager ]] && grep -qx "nameserver $LAN_NS" "$RESOLV"
    report $? "disconnect puts DNS back on NetworkManager's entry" "$(ls "$RC_DIR"; cat "$RESOLV")"
    ! grep -q '^sudo:' "$CALLS"
    report $? "nothing outside the fakes was run through sudo" "$(cat "$CALLS")"
}

echo -e "${T_BLUE}========================================${T_NC}"
echo -e "${T_BLUE}DNS Persistence Integration Tests${T_NC}"
echo -e "${T_BLUE}========================================${T_NC}"

test_sandbox
test_kill_9_state_reproduced
test_cleanup_after_kill_9 with-nm-entry kill-switch
test_cleanup_after_kill_9 no-nm-entry no-kill-switch
test_cleanup_foreign_resolv_conf
test_cleanup_keeps_state_of_running_wireguard
test_cleanup_stops_hung_openvpn
test_stale_check_keeps_state_while_tun0_exists
test_connect_sequence
test_disconnect_removes_everything

echo ""
echo -e "${T_BLUE}Results: $TESTS_PASSED/$TESTS_RUN passed${T_NC}"
if [[ $TESTS_FAILED -gt 0 ]]; then
    for t in "${FAILED_TESTS[@]}"; do echo -e "  ${T_RED}✗${T_NC} $t"; done
    exit 1
fi
exit 0
