#!/bin/bash
# ABOUTME: Behavioural tests: while connected, IPv6 is blocked and DNS bypasses Tailscale
# ABOUTME: Covers the ip6tables guard, pausing/restoring Tailscale DNS, opt-outs and release
# shellcheck disable=SC2319  # `report $?` deliberately reports the [[ ]] check above it

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
SRC_DIR="$PROJECT_ROOT/src"

TESTS_RUN=0
TESTS_PASSED=0
TESTS_FAILED=0
declare -a FAILED_TESTS=()

T_GREEN='\033[1;32m'
T_RED='\033[1;31m'
T_BLUE='\033[1;34m'
T_NC='\033[0m'

test_pass() {
    TESTS_RUN=$((TESTS_RUN + 1))
    TESTS_PASSED=$((TESTS_PASSED + 1))
    echo -e "  ${T_GREEN}✓${T_NC} $1"
}

test_fail() {
    TESTS_RUN=$((TESTS_RUN + 1))
    TESTS_FAILED=$((TESTS_FAILED + 1))
    FAILED_TESTS+=("$1")
    echo -e "  ${T_RED}✗${T_NC} $1"
    [[ -n "${2:-}" ]] && echo -e "    $2"
}

# report <exit-code> <name> [detail]
report() {
    if [[ $1 -eq 0 ]]; then
        test_pass "$2"
    else
        test_fail "$2" "${3:-}"
    fi
}

WORK_DIR=$(mktemp -d)
trap 'rm -rf "$WORK_DIR"' EXIT

# Isolated environment: nothing here may touch the real system. The scripts
# prefer installed copies in /usr/local/bin, so every test points VPN_DIR at
# stubs and replaces sudo, resolvconf, tailscale, pgrep and ip.
export HOME="$WORK_DIR/home"
export XDG_RUNTIME_DIR="$WORK_DIR/run"
export XDG_STATE_HOME="$HOME/.local/state"
export XDG_CACHE_HOME="$HOME/.cache"
export XDG_CONFIG_HOME="$HOME/.config"
export VPN_SESSION_DIR="$WORK_DIR/session"
export VPN_DNS_HELPER="$WORK_DIR/no-dns-helper"
export VPN_LOG_DIR="$XDG_STATE_HOME/vpn"
mkdir -p "$HOME/.config/vpn/locations" "$XDG_RUNTIME_DIR" "$VPN_LOG_DIR"
chmod 700 "$XDG_RUNTIME_DIR"

STUB_DIR="$WORK_DIR/stub"   # replaces VPN_DIR (vpn-kill-switch)
PATH_STUBS="$WORK_DIR/path" # first on PATH (resolvconf, tailscale, sudo, ...)
CALLS="$WORK_DIR/calls.log" # every stub appends what it was asked to do
TS_CORPDNS="$WORK_DIR/ts_corpdns"
TS_DOWN="$WORK_DIR/ts_down" # tailscaled not running while this exists
PAUSED="$XDG_STATE_HOME/vpn/tailscale-dns-paused"
export VPN_RESOLV_CONF="$WORK_DIR/resolv.conf"       # stands in for /etc/resolv.conf
export VPN_NM_RESOLV_CONF="$WORK_DIR/nm-resolv.conf" # NetworkManager's own copy
export VPN_TAILSCALE_TAKEOVER_WAIT=1 # seconds to wait for Tailscale to take DNS back
export CALLS TS_CORPDNS TS_DOWN WORK_DIR
mkdir -p "$STUB_DIR" "$PATH_STUBS"

cat > "$STUB_DIR/vpn-kill-switch" << 'EOF'
#!/bin/bash
echo "kill-switch:$*" >> "$CALLS"
[[ $1 == is-enabled ]] && exit 1
exit 0
EOF
cat > "$PATH_STUBS/tailscale" << 'EOF'
#!/bin/bash
if [[ $1 == debug && $2 == prefs ]]; then
    [[ -f $TS_DOWN ]] && { echo "failed to connect to local tailscaled" >&2; exit 1; }
    printf '{\n\t"CorpDNS": %s,\n\t"WantRunning": true\n}\n' "$(cat "$TS_CORPDNS")"
    exit 0
fi
echo "tailscale:$*" >> "$CALLS"
if [[ $1 == set ]]; then
    case "$2" in
        --accept-dns=false) echo false > "$TS_CORPDNS" ;;
        --accept-dns=true)
            echo true > "$TS_CORPDNS"
            if grep -q '^nameserver' "$VPN_RESOLV_CONF" 2> /dev/null; then
                echo "tailscale:upstream=yes" >> "$CALLS"
            else
                echo "tailscale:upstream=none" >> "$CALLS"
            fi
            [[ -f $WORK_DIR/ts_no_takeover ]] || printf 'nameserver 100.100.100.100\n' > "$VPN_RESOLV_CONF"
            ;;
    esac
fi
EOF
cat > "$PATH_STUBS/resolvconf" << 'EOF'
#!/bin/bash
if [[ $1 == -i ]]; then
    cat "$WORK_DIR/rc_ifaces" 2> /dev/null
    exit 0
fi
echo "resolvconf:$*" >> "$CALLS"
EOF
cat > "$PATH_STUBS/pgrep" << 'EOF'
#!/bin/bash
exit 1
EOF
cat > "$PATH_STUBS/ip" << 'EOF'
#!/bin/bash
exit 0
EOF
# Only the stubbed tools may run; anything else is recorded, never run
cat > "$PATH_STUBS/sudo" << 'EOF'
#!/bin/bash
[[ $1 == -n ]] && shift
case "$1" in resolvconf | tailscale) exec "$@" ;; esac
[[ $1 == install && ${*: -1} == "$WORK_DIR"/* ]] && exec "$@"
echo "sudo:$*" >> "$CALLS"
EOF
chmod +x "$STUB_DIR"/* "$PATH_STUBS"/*

# Fresh state: Tailscale running with MagicDNS on, nothing paused, no config
reset_state() {
    : > "$CALLS"
    echo true > "$TS_CORPDNS"
    rm -f "$TS_DOWN" "$PAUSED" "$WORK_DIR/rc_ifaces" "$WORK_DIR/ts_no_takeover"
    : > "$HOME/.config/vpn/config"
    # What openresolv leaves after the VPN entry is removed and NetworkManager
    # does not use resolvconf: a file without nameservers
    printf '# Generated by resolvconf\n' > "$VPN_RESOLV_CONF"
    printf 'nameserver 192.0.2.53\n' > "$VPN_NM_RESOLV_CONF"
}

# Shell code that loads a script with every system access stubbed
# Args: $1 = script in src/ to source
stubbed_source() {
    cat << EOF
source "$SRC_DIR/$1" > /dev/null 2>&1
source "$SRC_DIR/vpn-utils"
set +e
VPN_DIR="$STUB_DIR"
PATH="$PATH_STUBS:\$PATH"
log_vpn_event() { :; }
log_message() { :; }
notify_event() { :; }
pkill() { :; }
save_reconnect_state() { :; }
EOF
}

# A connect that just succeeded (the real success path, stubbed system)
run_connection_success() {
    bash -c "$(stubbed_source vpn-connector)
        handle_connection_success prof 1 1 ''" > /dev/null 2>&1
}

run_release() {
    bash -c "$(stubbed_source vpn-manager)
        release_vpn_network_state" > /dev/null 2>&1
}

called() { grep -qxF -- "$1" "$CALLS"; }

# ---------------------------------------------------------------------------
# On connect
# ---------------------------------------------------------------------------
test_connect_blocks_ipv6() {
    reset_state
    run_connection_success
    called "kill-switch:ipv6-guard on"
    report $? "a successful connect blocks IPv6 outside the tunnel" "$(cat "$CALLS")"

    reset_state
    echo "BLOCK_IPV6=false" > "$HOME/.config/vpn/config"
    run_connection_success
    ! called "kill-switch:ipv6-guard on"
    report $? "BLOCK_IPV6=false leaves IPv6 alone" "$(cat "$CALLS")"
}

test_connect_pauses_tailscale_dns() {
    reset_state
    run_connection_success
    called "tailscale:set --accept-dns=false"
    report $? "a successful connect pauses Tailscale DNS" "$(cat "$CALLS")"
    [[ -f $PAUSED ]]
    report $? "pausing Tailscale DNS is recorded for the restore" "no $PAUSED"
    called "resolvconf:-u"
    report $? "resolv.conf is regenerated from resolvconf (VPN DNS)" "$(cat "$CALLS")"
}

# The sleep and network hooks run the connector as root for the user, then
# read last_profile back as the user. A root-owned 0600 copy made every
# auto-reconnect after the first one fail, with the kill switch blocking
# everything. A user namespace gives EUID 0 without touching the system;
# chown is recorded (the namespace cannot hand files to another user).
run_state_writers() { # $1 = command prefix (empty: run unprivileged)
    local profile="$HOME/.config/vpn/locations/se-1.ovpn"
    echo client > "$profile"
    $1 bash -c "$(stubbed_source vpn-utils)
        secure_user_dir() { :; }
        chown() { echo \"chown:\$*\" >> \"\$CALLS\"; }
        REAL_USER=alice REAL_GROUP=staff
        eval \"\$(sed -n '/^save_reconnect_state() {/,/^}/p' '$SRC_DIR/vpn-connector')\"
        save_reconnect_state '$profile'
        pause_tailscale_dns" > /dev/null 2>&1
}

test_root_run_leaves_state_to_user() {
    local state="$XDG_STATE_HOME/vpn" missing="" f
    if ! unshare -r true 2> /dev/null; then
        test_pass "state written as root stays the user's (skipped: no user namespace)"
        return
    fi
    reset_state
    run_state_writers "unshare -r"
    for f in last_profile last_profile.sha256 tailscale-dns-paused; do
        called "chown:-h alice:staff $state/$f" || missing+=" $f"
    done
    [[ -z $missing ]]
    report $? "state written as root (hooks) is handed to the real user" "not chowned:$missing; $(cat "$CALLS")"

    reset_state
    run_state_writers ""
    ! grep -q "^chown:" "$CALLS"
    report $? "an unprivileged connect never chowns" "$(cat "$CALLS")"
}

test_tailscale_dns_left_alone() {
    reset_state
    echo "TAILSCALE_DNS=keep" > "$HOME/.config/vpn/config"
    run_connection_success
    ! grep -q "^tailscale:" "$CALLS" && [[ ! -f $PAUSED ]]
    report $? "TAILSCALE_DNS=keep leaves Tailscale DNS alone" "$(cat "$CALLS")"

    reset_state
    echo false > "$TS_CORPDNS"
    run_connection_success
    ! grep -q "^tailscale:" "$CALLS" && [[ ! -f $PAUSED ]]
    report $? "Tailscale DNS already off: nothing changed or recorded" "$(cat "$CALLS")"

    reset_state
    touch "$TS_DOWN"
    run_connection_success
    ! grep -q "^tailscale:" "$CALLS" && [[ ! -f $PAUSED ]]
    report $? "tailscaled not running: nothing changed" "$(cat "$CALLS")"
}

# ---------------------------------------------------------------------------
# On release (disconnect, stale state on connect, interrupted connect)
# ---------------------------------------------------------------------------
test_release_restores() {
    reset_state
    run_connection_success
    : > "$CALLS"
    run_release
    called "tailscale:set --accept-dns=true"
    report $? "release restores Tailscale DNS that was paused" "$(cat "$CALLS")"
    [[ ! -f $PAUSED ]]
    report $? "release clears the pause record" "still there: $PAUSED"
    called "kill-switch:ipv6-guard off"
    report $? "release removes the IPv6 block" "$(cat "$CALLS")"
}

test_release_respects_user_setting() {
    # The user turned Tailscale DNS off themselves: never turn it back on
    reset_state
    echo false > "$TS_CORPDNS"
    run_release
    ! grep -q "^tailscale:" "$CALLS"
    report $? "release never enables Tailscale DNS it did not pause" "$(cat "$CALLS")"
}

test_release_with_keep_kill_switch() {
    reset_state
    run_connection_success
    : > "$CALLS"
    bash -c "VPN_KEEP_KILL_SWITCH=1; $(stubbed_source vpn-manager)
        release_vpn_network_state" > /dev/null 2>&1
    called "tailscale:set --accept-dns=true" && called "kill-switch:ipv6-guard off"
    report $? "VPN_KEEP_KILL_SWITCH=1 still restores DNS and removes the IPv6 block" "$(cat "$CALLS")"
}

# After disconnect, openresolv rebuilds resolv.conf from its own entries only.
# NetworkManager here does not register with resolvconf, so removing the VPN
# entry left no nameservers: DNS was dead, and Tailscale (re-enabled after)
# backed up that empty file as its upstream, so only *.ts.net resolved.
test_release_restores_system_dns() {
    reset_state
    run_release
    grep -qx "nameserver 192.0.2.53" "$VPN_RESOLV_CONF"
    report $? "release puts NetworkManager's DNS back when resolv.conf has none" "$(cat "$VPN_RESOLV_CONF")"

    reset_state
    run_connection_success
    printf '# Generated by resolvconf\n' > "$VPN_RESOLV_CONF"
    : > "$CALLS"
    run_release
    called "tailscale:upstream=yes"
    report $? "Tailscale gets a working upstream when its DNS is restored" "$(cat "$CALLS")"

    reset_state
    printf 'nameserver 198.51.100.1\n' > "$VPN_RESOLV_CONF"
    run_release
    grep -qx "nameserver 198.51.100.1" "$VPN_RESOLV_CONF" && ! grep -q 192.0.2.53 "$VPN_RESOLV_CONF"
    report $? "a resolv.conf that still has nameservers is left alone" "$(cat "$VPN_RESOLV_CONF")"

    reset_state
    rm -f "$VPN_NM_RESOLV_CONF"
    run_release
    [[ $(cat "$VPN_RESOLV_CONF") == "# Generated by resolvconf" ]]
    report $? "no NetworkManager copy: resolv.conf is not touched" "$(cat "$VPN_RESOLV_CONF")"
}

# Tailscale in resolvconf mode (it registers a "tailscale" entry instead of
# writing resolv.conf itself) needs openresolv to own resolv.conf: copying
# NetworkManager's file in made every later `resolvconf -a tailscale` fail
# with "signature mismatch", so MagicDNS never came back.
test_release_tailscale_resolvconf_mode() {
    reset_state
    echo tailscale > "$WORK_DIR/rc_ifaces"
    run_connection_success
    grep -qx "mode=resolvconf" "$PAUSED" 2> /dev/null
    report $? "pause records that Tailscale uses resolvconf" "$(cat "$PAUSED" 2> /dev/null)"

    printf '# Generated by resolvconf\n' > "$VPN_RESOLV_CONF"
    : > "$CALLS"
    run_release
    ! grep -q 192.0.2.53 "$VPN_RESOLV_CONF" && called "resolvconf:-u" &&
        [[ $(grep -n "resolvconf:-u" "$CALLS" | head -1 | cut -d: -f1) -lt $(grep -n "tailscale:set --accept-dns=true" "$CALLS" | cut -d: -f1) ]]
    report $? "resolvconf-mode Tailscale: resolv.conf rebuilt by resolvconf, not copied, before Tailscale returns" \
        "$(cat "$CALLS"; cat "$VPN_RESOLV_CONF")"
}

# Re-enabling Tailscale DNS is no proof that it took resolv.conf back
test_tailscale_takeover_checked() {
    reset_state
    run_connection_success
    local out
    out=$(bash -c "$(stubbed_source vpn-manager)
        release_vpn_network_state" 2>&1)
    ! grep -qi "magicdns" <<< "$out"
    report $? "no warning when Tailscale takes DNS back" "$out"

    reset_state
    run_connection_success
    touch "$WORK_DIR/ts_no_takeover"
    out=$(bash -c "$(stubbed_source vpn-manager)
        release_vpn_network_state" 2>&1)
    grep -qi "magicdns" <<< "$out" && grep -q "restart tailscaled" <<< "$out"
    report $? "warns (MagicDNS, restart tailscaled) when Tailscale did not take DNS back" "$out"
}

# ---------------------------------------------------------------------------
# DNS helper vs a resolv.conf that openresolv did not write
# ---------------------------------------------------------------------------
# A fake openresolv with the real rule: -a/-d only rewrite resolv.conf when
# its first line is openresolv's signature, -u always does.
FAKE_RC="$WORK_DIR/fake_rc"
mkdir -p "$FAKE_RC/bin" "$FAKE_RC/entries"
cat > "$FAKE_RC/bin/resolvconf" << 'EOF'
#!/bin/bash
sig="# Generated by resolvconf"
regen() { # $1 = force
    if [[ $1 != force && -s $RC_FILE && $(head -1 "$RC_FILE") != "$sig" ]]; then
        echo "resolvconf: signature mismatch: $RC_FILE" >&2
        return 1
    fi
    local excl
    excl=$(ls "$RC_DIR"/*.excl 2> /dev/null | head -1)
    { echo "$sig"; if [[ -n $excl ]]; then cat "${excl%.excl}"; else cat "$RC_DIR"/* 2> /dev/null; fi; } > "$RC_FILE"
}
x=""
[[ $1 == -x ]] && { x=1; shift; }
case "$1" in
    -a) cat > "$RC_DIR/$2"; [[ -n $x ]] && touch "$RC_DIR/$2.excl"; regen ;;
    -f) rm -f "$RC_DIR/$3" "$RC_DIR/$3.excl"; regen ;;
    -d) rm -f "$RC_DIR/$2" "$RC_DIR/$2.excl"; regen ;;
    -u) regen force ;;
    -l) cat "$RC_DIR/$2" 2> /dev/null ;;
    -i) ls "$RC_DIR" | grep -v '\.excl$' ;;
esac
EOF
chmod +x "$FAKE_RC/bin/resolvconf"

# Args: $1 = script_type (up/down)
run_dns_helper() {
    env -i PATH="$FAKE_RC/bin:/usr/bin:/bin" RC_DIR="$FAKE_RC/entries" RC_FILE="$FAKE_RC/resolv.conf" \
        VPN_RESOLV_CONF="$FAKE_RC/resolv.conf" \
        script_type="$1" dev=tun0 'foreign_option_1=dhcp-option DNS 10.2.0.1' \
        sh "$SRC_DIR/vpn-dns-update" > /dev/null 2>&1
}

test_dns_helper_foreign_resolv_conf() {
    rm -f "$FAKE_RC/entries"/*
    printf '# Generated by NetworkManager\nnameserver 192.0.2.53\n' > "$FAKE_RC/resolv.conf"
    run_dns_helper up
    grep -qx "nameserver 10.2.0.1" "$FAKE_RC/resolv.conf" && ! grep -q 192.0.2.53 "$FAKE_RC/resolv.conf"
    report $? "VPN DNS applied over NetworkManager's resolv.conf" "$(cat "$FAKE_RC/resolv.conf")"

    # Tailscale's file is left to the connector: it pauses Tailscale DNS and
    # rebuilds resolv.conf, or keeps it on purpose with TAILSCALE_DNS=keep
    rm -f "$FAKE_RC/entries"/*
    printf '# resolv.conf(5) file generated by tailscale\nnameserver 100.100.100.100\n' > "$FAKE_RC/resolv.conf"
    run_dns_helper up
    grep -qx "nameserver 100.100.100.100" "$FAKE_RC/resolv.conf" && [[ -e $FAKE_RC/entries/tun0.protonvpn ]]
    report $? "Tailscale's resolv.conf is not overwritten (entry registered for later)" \
        "$(ls "$FAKE_RC/entries"; cat "$FAKE_RC/resolv.conf")"

    rm -f "$FAKE_RC/entries"/*
    printf '# Generated by resolvconf\nnameserver 192.0.2.53\n' > "$FAKE_RC/resolv.conf"
    run_dns_helper up
    grep -qx "nameserver 10.2.0.1" "$FAKE_RC/resolv.conf"
    report $? "VPN DNS applied over openresolv's own resolv.conf" "$(cat "$FAKE_RC/resolv.conf")"
    run_dns_helper down
    [[ ! -e $FAKE_RC/entries/tun0.protonvpn ]] && ! grep -q 10.2.0.1 "$FAKE_RC/resolv.conf"
    report $? "VPN DNS removed on down" "$(ls "$FAKE_RC/entries"; cat "$FAKE_RC/resolv.conf")"
}

# ---------------------------------------------------------------------------
# Real ip6tables in a private network namespace (no effect on the host)
# ---------------------------------------------------------------------------
netns_cmd=""
if command -v ip6tables > /dev/null; then
    if unshare -n true 2> /dev/null; then
        netns_cmd="unshare -n"
    elif unshare -rn ip6tables -S > /dev/null 2>&1; then
        netns_cmd="unshare -rn"
    fi
fi

test_ipv6_guard_netns() {
    if [[ -z $netns_cmd ]]; then
        test_pass "IPv6 guard in netns (skipped: no network namespace/ip6tables)"
        return
    fi
    local out
    # shellcheck disable=SC2016  # expanded inside the namespace shell
    out=$($netns_cmd bash -c '
        bash "$1/vpn-kill-switch" ipv6-guard on > /dev/null 2>&1 || echo "ON_FAILED"
        bash "$1/vpn-kill-switch" ipv6-guard on > /dev/null 2>&1 || echo "ON_FAILED"
        echo "jumps=$(ip6tables -S OUTPUT | grep -c VPN_IPV6_GUARD)"
        echo "v4=$(iptables -S | grep -c VPN_IPV6_GUARD)"
        ip6tables -S VPN_IPV6_GUARD
        bash "$1/vpn-kill-switch" ipv6-guard status > /dev/null 2>&1 && echo "status=on" || echo "status=off"
        ip6tables -A OUTPUT -j VPN_IPV6_GUARD
        bash "$1/vpn-kill-switch" ipv6-guard off > /dev/null 2>&1
        echo "left=$(ip6tables -S | grep -c VPN_IPV6_GUARD)"
        bash "$1/vpn-kill-switch" ipv6-guard status > /dev/null 2>&1 && echo "after=on" || echo "after=off"
    ' _ "$SRC_DIR" 2>&1)
    if grep -q "FAILED" <<< "$out"; then
        test_fail "ipv6-guard on in netns" "$out"
        return
    fi
    grep -q "jumps=1" <<< "$out"
    report $? "ipv6-guard on twice keeps a single OUTPUT jump" "$out"
    grep -q "v4=0" <<< "$out"
    report $? "IPv4 is not touched" "$out"
    local rule bad=""
    for rule in "-o lo -j ACCEPT" "-d fe80::/10 -j ACCEPT" "-d ff00::/8 -j ACCEPT" \
        "-o tun+ -j ACCEPT" "-o tailscale0 -j ACCEPT" "-o virbr+ -j ACCEPT"; do
        grep -q -- "-A VPN_IPV6_GUARD $rule" <<< "$out" || bad+=" [$rule]"
    done
    [[ -z $bad ]]
    report $? "allows loopback, link-local, multicast, tun, tailscale0, virbr" "missing:$bad"
    # REJECT needs a kernel module that cannot load in a user namespace (or
    # after a kernel upgrade without reboot); DROP is the fallback
    local last
    last=$(grep -- "-A VPN_IPV6_GUARD" <<< "$out" | tail -1)
    [[ $last == *"-j REJECT"* || $last == *"-j DROP" ]]
    report $? "everything else is rejected, or dropped without REJECT support" "$out"
    grep -q "status=on" <<< "$out" && grep -q "after=off" <<< "$out"
    report $? "ipv6-guard status reflects on/off" "$out"
    grep -q "left=0" <<< "$out"
    report $? "ipv6-guard off removes the chain and every jump" "$out"
}

echo -e "${T_BLUE}========================================${T_NC}"
echo -e "${T_BLUE}Leak Protection Test Suite${T_NC}"
echo -e "${T_BLUE}========================================${T_NC}"

test_connect_blocks_ipv6
test_connect_pauses_tailscale_dns
test_tailscale_dns_left_alone
test_root_run_leaves_state_to_user
test_release_restores
test_release_respects_user_setting
test_release_with_keep_kill_switch
test_release_restores_system_dns
test_release_tailscale_resolvconf_mode
test_tailscale_takeover_checked
test_dns_helper_foreign_resolv_conf
test_ipv6_guard_netns

echo ""
echo -e "${T_BLUE}Results: $TESTS_PASSED/$TESTS_RUN passed${T_NC}"
if [[ $TESTS_FAILED -gt 0 ]]; then
    for t in "${FAILED_TESTS[@]}"; do echo -e "  ${T_RED}✗${T_NC} $t"; done
    exit 1
fi
exit 0
