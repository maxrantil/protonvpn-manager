#!/bin/bash
# ABOUTME: Tests for vpn_dns_mismatch and vpn_dns_state (vpn-utils): resolv.conf vs. the VPN's DNS, guard state
# ABOUTME: Fake resolvconf and kill switch in a sandbox PATH; nothing real is read or changed
# shellcheck disable=SC2319  # `report $?` deliberately reports the [[ ]] check above it

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
SRC_DIR="$PROJECT_ROOT/src"

TESTS_RUN=0
TESTS_PASSED=0
TESTS_FAILED=0
declare -a FAILED_TESTS=()

T_GREEN='\033[1;32m'
T_RED='\033[1;31m'
T_BLUE='\033[1;34m'
T_NC='\033[0m'

test_pass() {
    TESTS_RUN=$((TESTS_RUN + 1))
    TESTS_PASSED=$((TESTS_PASSED + 1))
    echo -e "  ${T_GREEN}✓${T_NC} $1"
}

test_fail() {
    TESTS_RUN=$((TESTS_RUN + 1))
    TESTS_FAILED=$((TESTS_FAILED + 1))
    FAILED_TESTS+=("$1")
    echo -e "  ${T_RED}✗${T_NC} $1"
    [[ -n "${2:-}" ]] && echo -e "    $2"
}

# report <exit-code> <name> [detail]
report() {
    if [[ $1 -eq 0 ]]; then
        test_pass "$2"
    else
        test_fail "$2" "${3:-}"
    fi
}

WORK_DIR=$(mktemp -d)
trap 'rm -rf "$WORK_DIR"' EXIT

# Sandbox: the fakes plus every system tool except those that touch DNS,
# the firewall or privileges
FAKES="$WORK_DIR/fakes"
SYSBIN="$WORK_DIR/sysbin"
KS_DIR="$WORK_DIR/ks" # VPN_DIR: holds the fake vpn-kill-switch
RC="$WORK_DIR/rc"     # fake resolvconf state
CALLS="$WORK_DIR/calls.log"
RESOLV="$WORK_DIR/resolv.conf"
CONF_DIR="$WORK_DIR/config"
mkdir -p "$FAKES" "$SYSBIN" "$KS_DIR" "$RC/entries" "$CONF_DIR" "$WORK_DIR/home"
ln -s /usr/bin/* "$SYSBIN"/ 2> /dev/null
for tool in iptables ip6tables iptables-restore ip6tables-restore iptables-nft ip6tables-nft \
    iptables-legacy ip6tables-legacy nft sudo doas su pkexec resolvconf nmcli tailscale \
    openvpn systemctl rc-service; do
    rm -f "$SYSBIN/$tool"
done

# resolvconf: --version prints $RC/version; -l <entry> prints the entry as
# openresolv does (a comment, then its lines), nothing for an unknown one.
# Anything else would change DNS: recorded, and fails.
cat > "$FAKES/resolvconf" << 'EOF'
#!/bin/bash
case "$1" in
    --version) cat "$RC/version" ;;
    -l)
        if [[ -f $RC/entries/$2 ]]; then
            echo "# resolv.conf from $2"
            cat "$RC/entries/$2"
        fi
        ;;
    *)
        echo "resolvconf:$*" >> "$CALLS"
        exit 1
        ;;
esac
EOF
cat > "$FAKES/sudo" << 'EOF'
#!/bin/bash
echo "sudo:$*" >> "$CALLS"
exit 1
EOF
# The kill switch's `dns-guard status`: prints $RC/guard_out, exits $RC/guard_rc
cat > "$KS_DIR/vpn-kill-switch" << 'EOF'
#!/bin/bash
echo "kill-switch:$*" >> "$CALLS"
[[ "$*" == "dns-guard status" ]] || exit 1
cat "$RC/guard_out"
exit "$(cat "$RC/guard_rc")"
EOF
chmod +x "$FAKES/resolvconf" "$FAKES/sudo" "$KS_DIR/vpn-kill-switch"
SANDBOX_PATH="$FAKES:$SYSBIN"

# Fresh state: openresolv, the VPN's entry 10.96.0.1, resolv.conf matching,
# guard on, empty config
reset_dns() {
    rm -rf "$RC/entries" "$RESOLV" "$CONF_DIR/config"
    mkdir -p "$RC/entries"
    echo "openresolv 3.13.2" > "$RC/version"
    printf 'nameserver 10.96.0.1\n' > "$RC/entries/tun0.protonvpn"
    printf '# Generated by resolvconf\nnameserver 10.96.0.1\n' > "$RESOLV"
    guard on 0
    : > "$CALLS"
}

# guard <status text> <exit code>
guard() {
    echo "$1" > "$RC/guard_out"
    echo "$2" > "$RC/guard_rc"
}

# Run a snippet with vpn-utils sourced, under the callers' shell options
in_sandbox() {
    env -i HOME="$WORK_DIR/home" PATH="$SANDBOX_PATH" RC="$RC" CALLS="$CALLS" \
        VPN_RESOLV_CONF="$RESOLV" VPN_CONFIG_DIR="$CONF_DIR" VPN_DIR="$KS_DIR" \
        "$BASH" -c 'set -euo pipefail; source "$1"; shift; eval "$1"' _ "$SRC_DIR/vpn-utils" "$1"
}

# Mismatch check; sets OUT and RC_
mismatch() {
    OUT=$(in_sandbox 'vpn_dns_mismatch' 2>&1) && RC_=0 || RC_=$?
}

# State for "VPN running" ($1 = yes|no); OUT holds "guard=<state>" then one
# "warn=<text>" line per warning
dns_state() {
    OUT=$(in_sandbox "vpn_dns_state $1; echo \"guard=\$VPN_DNS_GUARD\"; for w in \"\${VPN_DNS_WARNINGS[@]}\"; do echo \"warn=\$w\"; done" 2>&1) && RC_=0 || RC_=$?
}

# ---------------------------------------------------------------------------
# vpn_dns_mismatch
# ---------------------------------------------------------------------------
test_sandbox() {
    local tool found bad=""
    for tool in resolvconf sudo; do
        found=$(env PATH="$SANDBOX_PATH" bash -c "command -v $tool")
        [[ $found == "$FAKES/$tool" ]] || bad+=" $tool=$found"
    done
    for tool in iptables nmcli tailscale; do
        found=$(env PATH="$SANDBOX_PATH" bash -c "command -v $tool")
        [[ -z $found ]] || bad+=" $tool=$found"
    done
    [[ -z $bad ]]
    report $? "only the fake resolvconf and sudo are reachable" "$bad"
}

test_match() {
    reset_dns
    mismatch
    [[ $RC_ -eq 1 && -z $OUT ]]
    report $? "resolv.conf on the VPN's DNS: no mismatch, no output" "rc=$RC_ out=$OUT"
}

test_mismatch() {
    reset_dns
    printf '# Generated by NetworkManager\nsearch lan\nnameserver 172.20.10.1\n' > "$RESOLV"
    mismatch
    [[ $RC_ -eq 0 ]]
    report $? "resolv.conf on the router's DNS is a mismatch" "rc=$RC_ out=$OUT"
    [[ $OUT == *"expected: 10.96.0.1"* && $OUT == *"actual: 172.20.10.1"* ]]
    report $? "a mismatch prints both sets" "$OUT"
}

test_sets() {
    reset_dns
    printf 'nameserver 10.96.0.1\nnameserver 10.96.0.2\n' > "$RC/entries/tun0.protonvpn"
    printf 'nameserver 10.96.0.2\nnameserver 10.96.0.1\n' > "$RESOLV"
    mismatch
    [[ $RC_ -eq 1 ]]
    report $? "several nameservers in another order match" "rc=$RC_ out=$OUT"

    printf 'nameserver 10.96.0.1\n' > "$RESOLV"
    mismatch
    [[ $RC_ -eq 0 ]]
    report $? "a missing VPN nameserver is a mismatch" "rc=$RC_"

    printf 'nameserver 10.96.0.1\nnameserver 10.96.0.2\nnameserver 192.168.1.1\n' > "$RESOLV"
    mismatch
    [[ $RC_ -eq 0 && $OUT == *"actual: 10.96.0.1 10.96.0.2 192.168.1.1"* ]]
    report $? "an extra non-VPN nameserver is a mismatch" "rc=$RC_ out=$OUT"

    printf 'nameserver 10.96.0.2\nnameserver 10.96.0.1\nnameserver 10.96.0.1\n' > "$RESOLV"
    mismatch
    [[ $RC_ -eq 1 ]]
    report $? "a nameserver listed twice still matches" "rc=$RC_ out=$OUT"

    printf 'nameserver FD00::1\n' > "$RC/entries/tun0.protonvpn"
    printf 'nameserver fd00::1\n' > "$RESOLV"
    mismatch
    [[ $RC_ -eq 1 ]]
    report $? "IPv6 addresses compare case-insensitively" "rc=$RC_ out=$OUT"
}

test_comments_and_search() {
    reset_dns
    printf '# nameserver 192.168.1.1\n;nameserver 192.168.1.2\nsearch lan\ndomain lan\noptions edns0\n  nameserver   10.96.0.1  \n' > "$RESOLV"
    mismatch
    [[ $RC_ -eq 1 ]]
    report $? "comments, search, domain and options lines are ignored" "rc=$RC_ out=$OUT"
    printf '# nameserver 172.20.10.1\nsearch lan\nnameserver 10.96.0.1\n' > "$RC/entries/tun0.protonvpn"
    printf 'nameserver 10.96.0.1\n' > "$RESOLV"
    mismatch
    [[ $RC_ -eq 1 ]]
    report $? "comments in the VPN's entry are ignored" "rc=$RC_ out=$OUT"
}

test_empty_or_unreadable() {
    reset_dns
    : > "$RESOLV"
    mismatch
    [[ $RC_ -eq 0 && $OUT == *"actual: "* ]]
    report $? "an empty resolv.conf is a mismatch" "rc=$RC_ out=$OUT"
    printf '# Generated by resolvconf\n' > "$RESOLV"
    mismatch
    [[ $RC_ -eq 0 ]]
    report $? "a resolv.conf without nameservers is a mismatch" "rc=$RC_"
    rm -f "$RESOLV"
    mismatch
    [[ $RC_ -eq 0 ]]
    report $? "a missing resolv.conf is a mismatch" "rc=$RC_ out=$OUT"
    mkdir "$RESOLV"
    mismatch
    [[ $RC_ -eq 0 ]]
    report $? "an unreadable resolv.conf is a mismatch" "rc=$RC_ out=$OUT"
    rmdir "$RESOLV"
}

test_skipped() {
    reset_dns
    printf 'nameserver 172.20.10.1\n' > "$RESOLV"
    rm -f "$RC/entries/tun0.protonvpn"
    mismatch
    [[ $RC_ -eq 1 && -z $OUT ]]
    report $? "no tun0.protonvpn entry: skipped silently" "rc=$RC_ out=$OUT"

    reset_dns
    printf 'nameserver 172.20.10.1\n' > "$RESOLV"
    echo "resolvconf from systemd" > "$RC/version"
    mismatch
    [[ $RC_ -eq 1 && -z $OUT ]]
    report $? "a resolvconf that is not openresolv: skipped silently" "rc=$RC_ out=$OUT"

    reset_dns
    printf 'nameserver 172.20.10.1\n' > "$RESOLV"
    mv "$FAKES/resolvconf" "$WORK_DIR/resolvconf.off"
    mismatch
    mv "$WORK_DIR/resolvconf.off" "$FAKES/resolvconf"
    [[ $RC_ -eq 1 && -z $OUT ]]
    report $? "no resolvconf: skipped silently" "rc=$RC_ out=$OUT"

    reset_dns
    printf 'nameserver 100.100.100.100\n' > "$RESOLV"
    printf 'TAILSCALE_DNS="keep"\n' > "$CONF_DIR/config"
    mismatch
    [[ $RC_ -eq 1 && -z $OUT ]]
    report $? "TAILSCALE_DNS=keep: skipped silently" "rc=$RC_ out=$OUT"
}

test_read_only() {
    reset_dns
    printf 'nameserver 172.20.10.1\n' > "$RESOLV"
    mismatch
    dns_state yes
    [[ ! -s $CALLS || $(grep -cv '^kill-switch:dns-guard status$' "$CALLS") -eq 0 ]]
    report $? "the checks change nothing and never use sudo" "$(cat "$CALLS")"
}

# ---------------------------------------------------------------------------
# vpn_dns_state: what status and doctor print
# ---------------------------------------------------------------------------
test_state_connected_ok() {
    reset_dns
    dns_state yes
    [[ $RC_ -eq 0 && $OUT == "guard=on" ]]
    report $? "connected, DNS on the VPN, guard on: no warnings" "rc=$RC_ out=$OUT"
    [[ $(grep -c '^kill-switch:' "$CALLS") -eq 1 ]]
    report $? "the guard's state is read once" "$(cat "$CALLS")"
}

test_state_mismatch() {
    reset_dns
    printf 'nameserver 172.20.10.1\n' > "$RESOLV"
    dns_state yes
    [[ $OUT == *"warn=DNS is not using the VPN (resolv.conf: 172.20.10.1). Fix: sudo resolvconf -u"* ]]
    report $? "connected with a mismatch: the PDR's warning" "$OUT"
    : > "$RESOLV"
    dns_state yes
    [[ $OUT == *"warn=DNS is not using the VPN (resolv.conf: no nameserver). Fix: sudo resolvconf -u"* ]]
    report $? "connected with an empty resolv.conf: says no nameserver" "$OUT"
}

test_state_guard_off() {
    reset_dns
    guard off 1
    dns_state yes
    [[ $OUT == *"guard=off"* && $OUT == *"warn=DNS guard is off while connected"* ]]
    report $? "connected, guard off: warns" "$OUT"
    printf 'BLOCK_DNS_LEAKS=false\n' > "$CONF_DIR/config"
    dns_state yes
    [[ $OUT == "guard=off" ]]
    report $? "connected, guard off, BLOCK_DNS_LEAKS=false: no warning" "$OUT"
}

test_state_guard_partial() {
    reset_dns
    guard "on (not first in OUTPUT)" 2
    dns_state yes
    [[ $OUT == *"guard=on (not first in OUTPUT)"* && $OUT == *"warn=DNS guard is incomplete (not first in OUTPUT)"* ]]
    report $? "connected, guard not first: warns" "$OUT"
    guard "on (IPv4 only)" 2
    dns_state yes
    [[ $OUT == *"warn=DNS guard is incomplete (IPv4 only)"* ]]
    report $? "connected, guard on one family only: warns" "$OUT"
}

test_state_unknown() {
    reset_dns
    guard unknown 2
    dns_state yes
    [[ $OUT == "guard=unknown" ]]
    report $? "guard unknown (no sudo): shown, never taken as off" "$OUT"
    dns_state no
    [[ $OUT == "guard=unknown" ]]
    report $? "guard unknown, disconnected: no leftover warning" "$OUT"
    rm -f "$KS_DIR/vpn-kill-switch.off"
    mv "$KS_DIR/vpn-kill-switch" "$KS_DIR/vpn-kill-switch.off"
    dns_state yes
    mv "$KS_DIR/vpn-kill-switch.off" "$KS_DIR/vpn-kill-switch"
    [[ $RC_ -eq 0 && $OUT == "guard=unknown" ]]
    report $? "no kill switch: guard unknown" "rc=$RC_ out=$OUT"
}

test_state_leftover() {
    reset_dns
    dns_state no
    [[ $OUT == *"warn=DNS is blocked by a leftover DNS guard. Fix: vpn cleanup"* ]]
    report $? "disconnected, guard on: leftover guard warning" "$OUT"
    guard "on (not first in OUTPUT)" 2
    dns_state no
    [[ $OUT == *"warn=DNS is blocked by a leftover DNS guard. Fix: vpn cleanup"* ]]
    report $? "disconnected, guard partly on: leftover guard warning" "$OUT"
}

test_state_disconnected_ok() {
    reset_dns
    guard off 1
    printf 'nameserver 192.168.1.1\n' > "$RESOLV"
    dns_state no
    [[ $RC_ -eq 0 && $OUT == "guard=off" ]]
    report $? "disconnected, guard off: no warnings (the mismatch is not checked)" "rc=$RC_ out=$OUT"
}

# ---------------------------------------------------------------------------
# vpn status: the lines it prints (show_dns_state, extracted from vpn-manager)
# ---------------------------------------------------------------------------
# $1 = yes|no (running), $2 = mode (plain | accessible); stubbed vpn_dns_state
status_lines() {
    (
        # shellcheck disable=SC1090  # function extracted from vpn-manager
        source <(sed -n '/^show_dns_state() {$/,/^}$/p' "$SRC_DIR/vpn-manager")
        set -euo pipefail
        # shellcheck disable=SC2034  # read by the sourced show_dns_state
        YELLOW="" BOLD="" NC=""
        # shellcheck disable=SC2034  # read by the sourced show_dns_state
        vpn_dns_state() {
            VPN_DNS_GUARD="on (not first in OUTPUT)"
            VPN_DNS_WARNINGS=()
            [[ $1 == yes ]] && VPN_DNS_WARNINGS=("first warning" "second warning")
            return 0
        }
        show_dns_state "$1" "$2"
    ) 2>&1
}

test_status_lines() {
    grep -q '^show_dns_state() {$' "$SRC_DIR/vpn-manager"
    report $? "vpn-manager defines show_dns_state"
    local out fn
    out=$(status_lines yes plain)
    [[ $out == *"DNS guard: on (not first in OUTPUT)"* && $out == *"[WARN]"*"first warning"* && $out == *"[WARN]"*"second warning"* ]]
    report $? "status prints the guard line and each warning" "$out"
    out=$(status_lines no plain)
    [[ $out == "  DNS guard: on (not first in OUTPUT)" ]]
    report $? "status without warnings prints only the guard line" "$out"
    out=$(status_lines yes accessible)
    [[ $out == *"DNS Guard: on (not first in OUTPUT)"* && $out == *"WARNING: first warning"* && $out != *"⚠"* ]]
    report $? "accessible status prints plain text lines" "$out"
    for fn in show_status show_status_accessible; do
        sed -n "/^$fn() {\$/,/^}\$/p" "$SRC_DIR/vpn-manager" | grep -q 'show_dns_state'
        report $? "$fn shows the DNS state"
    done
}

echo -e "${T_BLUE}========================================${T_NC}"
echo -e "${T_BLUE}DNS Mismatch and Guard State Test Suite${T_NC}"
echo -e "${T_BLUE}========================================${T_NC}"

test_sandbox
test_match
test_mismatch
test_sets
test_comments_and_search
test_empty_or_unreadable
test_skipped
test_read_only
test_state_connected_ok
test_state_mismatch
test_state_guard_off
test_state_guard_partial
test_state_unknown
test_state_leftover
test_state_disconnected_ok
test_status_lines

echo ""
echo -e "${T_BLUE}Results: $TESTS_PASSED/$TESTS_RUN passed${T_NC}"
if [[ $TESTS_FAILED -gt 0 ]]; then
    printf '  failed: %s\n' "${FAILED_TESTS[@]}"
    exit 1
fi
exit 0
